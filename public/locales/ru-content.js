export const ruContent = new Map();
const definitions = new Map([CLASSES, REWARDS, EVENTS, STATUSES, SHOP, MATCH_QUESTS, LIFETIME_QUESTS]
  .flatMap(collection => Object.values(collection).map(entry => [entry.id, entry])));
for (const row of rows) {
  const [id, name, description, innate] = row.split('|');
  const source = definitions.get(id);
  if (!source) throw new Error('Unknown Russian catalog entry ' + id);
  ruContent.set(source.name, name);
  ruContent.set(source.description, description);
  if (innate) {
    ruContent.set(source.innate, innate);
    const [talent, ...effect] = source.innate.split(': ');
    const [title, ...explanation] = innate.split(': ');
    ruContent.set(talent, title);
    const sentence = explanation.join(': ');
    ruContent.set(effect.join(': '), sentence[0].toUpperCase() + sentence.slice(1));
  }
}

